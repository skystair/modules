/* 头文件由lcd.c提供,此处不再重复包含 */
/* delay_ms/delay_us用lcd_delay近似替代: 约15000次循环≈1ms@72MHz */
#define delay_ms(x) lcd_delay((uint32_t)(x) * 15000)
#define delay_us(x) lcd_delay((uint32_t)(x) * 15)


/*****************************************************************************************************
 *                              数据表驱动结构定义 (8位地址IC通用)
 ****************************************************************************************************/

/**
 * @brief   LCD寄存器命令结构体 (用于8位地址的IC)
 * @note    格式: {寄存器地址, 数据长度, {数据0, 数据1, ...}}
 *          特殊标记:
 *            - cmd = 0xFE: 延时命令, len = 延时毫秒数
 *            - cmd = 0xFF: 表结束标记
 */
typedef struct {
    uint8_t cmd;        /* 寄存器地址 (0xFE=延时, 0xFF=结束) */
    uint8_t len;        /* 数据长度 (0~35) */
    uint8_t data[35];   /* 数据字节 (最多35字节) */
} lcd_cmd_t;

#define LCD_CMD_DELAY_US 0xFD   /* 微秒延时命令 */
#define LCD_CMD_DELAY   0xFE    /* 毫秒延时命令 */
#define LCD_CMD_END     0xFF    /* 表结束标记 */


/**
 * @brief       执行LCD命令表 (8位地址IC通用)
 * @param       cmds: 命令表指针
 * @retval      无
 */
static void lcd_exec_cmds(const lcd_cmd_t *cmds)
{
    while (cmds->cmd != LCD_CMD_END) {
        if (cmds->cmd == LCD_CMD_DELAY) {
            delay_ms(cmds->len);
        } else if (cmds->cmd == LCD_CMD_DELAY_US) {
            delay_us(cmds->len);
        } else {
            lcd_wr_regno(cmds->cmd);
            for (uint8_t i = 0; i < cmds->len; i++) {
                lcd_wr_data(cmds->data[i]);
            }
        }
        cmds++;
    }
}


/* NT35510专用16位地址命令结构体 */
typedef struct {
    uint16_t reg;           /* 16位寄存器地址 (0xFFFF=延时, 0xFFFE=结束) */
    uint16_t data;          /* 数据字节 */
} lcd_cmd16_t;

#define LCD_CMD16_DELAY 0xFFFF  /* 延时命令 */
#define LCD_CMD16_END   0xFFFE  /* 表结束标记 */

/**
 * @brief       执行NT35510命令表 (16位地址)
 * @param       cmds: 命令表指针
 * @retval      无
 */
static void lcd_exec_cmds16(const lcd_cmd16_t *cmds)
{
    while (cmds->reg != LCD_CMD16_END) {
        if (cmds->reg == LCD_CMD16_DELAY) {
            delay_ms(cmds->data);
        } else {
            lcd_write_reg(cmds->reg, cmds->data);
        }
        cmds++;
    }
}

